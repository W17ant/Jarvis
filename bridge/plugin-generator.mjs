/** plugin-generator.mjs — Voice-callable plugin scaffolding.
 *
 *  The wedge: a kiosk that builds its own tools. The operator says
 *  "hey jarvis, build me a plugin that fetches the top hacker news",
 *  the LLM calls `build_plugin(...)`, this module writes a manifest.json
 *  + handler.mjs into bridge/plugins/<slug>/, plugin-loader's fs.watch
 *  picks the directory up within 500ms, the new tool becomes callable
 *  in the same session.
 *
 *  Two modes:
 *
 *  1. STUB MODE (no `behaviour` arg) — writes a working plugin that
 *     returns a TODO string. The operator opens handler.mjs and fills
 *     in real logic. Useful when the operator already knows what they
 *     want to write but wants the boilerplate generated.
 *
 *  2. CODE-AGENT MODE (`behaviour` arg present) — writes a manifest
 *     synchronously then invokes code_agent_run with a templated prompt
 *     that knows the plugin authoring contract. The agent writes the
 *     handler. The operator hears one confirmation before the agent
 *     runs (standard code_agent_run gate); after it returns, the
 *     watcher hot-loads the result.
 *
 *  Why not always use the agent: agent runs cost LLM tokens and take
 *  time. For an operator who already knows what they want to write,
 *  the stub lets them skip both. The agent path is the killer demo,
 *  not the only path.
 *
 *  Security model:
 *    - The slug is regex-validated; no path traversal, no shell metas.
 *    - Tool name + voice intent are validated against the same regex
 *      the plugin loader uses for tool names.
 *    - The handler template only emits ASCII identifiers and JSON-quoted
 *      strings; none of the operator's free-form text lands in executable
 *      positions.
 *    - Plugin always lands at bridge/plugins/<slug>/, never elsewhere.
 *    - Existing plugins of the same slug are NOT silently overwritten;
 *      the caller gets an error. Use `force: true` to overwrite.
 *    - The fs.watch hot-reload + plugin-loader manifest validation
 *      are the second line of defence — a malformed generated plugin
 *      gets rejected at load with a clear log line.
 */

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PLUGINS_DIR = path.join(HERE, "plugins");

/* Slugs match the loader's manifest-name regex exactly so a generated plugin
 * never gets rejected for a name the generator allowed. */
const SLUG_RE = /^[a-z][a-z0-9-]{1,40}$/i;
/* Tool names follow the same regex the loader applies. Underscores allowed,
 * hyphens not (snake_case is the bridge's convention). */
const TOOL_NAME_RE = /^[a-z][a-z0-9_]{1,60}$/;

/** Compose the manifest.json content. Pure data — every operator-supplied
 *  string lands inside JSON.stringify so quotes and newlines are escaped. */
function _renderManifest({ slug, description, toolName, voiceIntent }) {
  return JSON.stringify({
    name: slug,
    version: "0.1.0",
    description,
    handler: "./handler.mjs",
    tools: [{
      name: toolName,
      description: `${description}. Voice intent: "${voiceIntent}".`,
      parameters: {
        type: "object",
        properties: {
          /* Keep the parameter surface intentionally tiny on stub plugins —
           * one optional `note` field. The operator can broaden it later
           * by editing manifest.json + handler.mjs together. */
          note: {
            type: "string",
            description: "Optional note from the operator's voice command. Free-form.",
          },
        },
        required: [],
      },
    }],
    env: [],
    /* Confirmation template uses {placeholder} substitution applied by
     * plugin-loader._renderConfirmTemplate. No code eval. */
    confirmation: {},
  }, null, 2) + "\n";
}

/** Compose handler.mjs for stub mode. Returns a string the operator can
 *  read, edit, and re-save (the watcher will hot-reload). */
function _renderStubHandler({ slug, toolName, voiceIntent, description }) {
  /* Each free-form field is JSON-stringified before injection so the
   * resulting source is always syntactically valid even if the operator
   * passed exotic characters (quotes, backslashes, newlines). */
  const safeSlug = JSON.stringify(slug);
  const safeTool = JSON.stringify(toolName);
  const safeIntent = JSON.stringify(voiceIntent);
  const safeDesc = JSON.stringify(description);

  return `/** ${slug} plugin handler — generated by build_plugin.
 *
 *  Description: ${description}
 *  Voice intent: "${voiceIntent}"
 *
 *  This is a STUB. Replace the body of run() with real logic.
 *  The plugin-loader hot-reloads on save (500ms debounce) — no restart
 *  needed. Errors thrown here surface as the tool's error to the LLM.
 *
 *  ctx primitives:
 *    ctx.executeTool(name, args)  – call any other registered tool
 *    ctx.broadcast(payload)       – push a WS event to the HUD
 *    ctx.memory                   – { put(k,v), get(k), list(prefix) }
 *    ctx.log(...)                 – tagged console.log (shows plugin name)
 */

const PLUGIN_NAME = ${safeSlug};
const TOOL_NAME = ${safeTool};
const VOICE_INTENT = ${safeIntent};

async function run(toolName, args, ctx) {
  /* TODO: replace with real logic.
   * args.note is the optional free-form string from the LLM.
   * Return any JSON-serialisable value; it's spoken back via TTS. */
  ctx.log?.(\`\${PLUGIN_NAME}: stub invoked with note=\`, args?.note);
  return {
    ok: true,
    summary: \`The \${PLUGIN_NAME} plugin is a stub. Open bridge/plugins/\${PLUGIN_NAME}/handler.mjs and replace the body of run() with real logic. Voice intent: ${voiceIntent}\`,
  };
}

export default run;
`;
}

/** Compose handler.mjs for code-agent mode — same shape as the stub but
 *  with a marker comment the agent will replace, and a hint about the
 *  contract. The agent overwrites the file before plugin-loader picks it
 *  up; if the agent fails, we fall back to the stub. */
function _renderAgentSeedHandler({ slug, toolName, voiceIntent, description, behaviour }) {
  const safeSlug = JSON.stringify(slug);
  const safeTool = JSON.stringify(toolName);
  const safeBehaviour = JSON.stringify(behaviour);
  return `/** ${slug} plugin handler — being written by code-agent.
 *  Behaviour spec: ${behaviour}
 *  This file will be rewritten by code_agent_run. */

const PLUGIN_NAME = ${safeSlug};
const TOOL_NAME = ${safeTool};
const BEHAVIOUR = ${safeBehaviour};

async function run(toolName, args, ctx) {
  return { ok: false, error: "agent did not finish writing this handler" };
}

export default run;
`;
}

/** Public API: scaffold a plugin from a spec.
 *
 *  @param {{
 *    name: string,
 *    description: string,
 *    toolName: string,
 *    voiceIntent: string,
 *    behaviour?: string | null,
 *    force?: boolean,
 *  }} spec
 *  @returns {Promise<{ ok: true, slug, path, toolName, mode } | { ok: false, error }>}
 */
export async function buildPlugin(spec) {
  const slug = String(spec?.name || "").trim().toLowerCase();
  const description = String(spec?.description || "").trim();
  const toolName = String(spec?.toolName || "").trim();
  const voiceIntent = String(spec?.voiceIntent || "").trim();
  const behaviour = spec?.behaviour ? String(spec.behaviour).trim() : null;
  const force = !!spec?.force;

  /* Up-front validation. Each branch returns a structured error so the
   * LLM can read the message and adjust if it gets a parameter wrong. */
  if (!SLUG_RE.test(slug)) {
    return { ok: false, error: `plugin name "${slug}" is invalid (must match /^[a-z][a-z0-9-]{1,40}$/i — e.g. "hackernews", "weather-pro")` };
  }
  if (!description) {
    return { ok: false, error: "description required (one-liner of what the plugin does)" };
  }
  if (!TOOL_NAME_RE.test(toolName)) {
    return { ok: false, error: `toolName "${toolName}" is invalid (must match /^[a-z][a-z0-9_]+$/ — snake_case, e.g. "fetch_top_hn")` };
  }
  if (!voiceIntent) {
    return { ok: false, error: "voiceIntent required (what the operator says to invoke this — e.g. 'top hacker news')" };
  }

  const pluginDir = path.join(PLUGINS_DIR, slug);
  /* If a plugin with this slug already exists, refuse to clobber unless
   * the operator explicitly passed force: true. The LLM doesn't get
   * force by default — the operator has to grant it via voice. */
  try {
    await fs.access(pluginDir);
    if (!force) {
      return { ok: false, error: `plugin "${slug}" already exists at bridge/plugins/${slug}/. Pass force: true to overwrite (operator confirmation required).` };
    }
  } catch { /* doesn't exist — fall through */ }

  await fs.mkdir(pluginDir, { recursive: true });

  const manifestPath = path.join(pluginDir, "manifest.json");
  await fs.writeFile(manifestPath, _renderManifest({ slug, description, toolName, voiceIntent }), "utf8");

  const handlerPath = path.join(pluginDir, "handler.mjs");
  const mode = behaviour ? "agent-seeded" : "stub";
  const handlerSrc = behaviour
    ? _renderAgentSeedHandler({ slug, toolName, voiceIntent, description, behaviour })
    : _renderStubHandler({ slug, toolName, voiceIntent, description });
  await fs.writeFile(handlerPath, handlerSrc, "utf8");

  return {
    ok: true,
    slug,
    path: pluginDir,
    toolName,
    voiceIntent,
    mode,
    /* Whether the caller still needs to invoke code_agent_run to fill
     * in real handler logic. Stub mode = no, agent mode = yes. The
     * server's tool dispatch chains the second call when this is true. */
    needsAgentFill: !!behaviour,
    /* Hint surfaced back through the LLM reply for the operator. Tells
     * them the new tool is callable + where to edit if they want to
     * tweak the logic by hand. */
    hint: behaviour
      ? `Plugin "${slug}" scaffolded. Code-agent is filling the handler now.`
      : `Plugin "${slug}" loaded. Tool "${toolName}" is callable on the next turn. Edit bridge/plugins/${slug}/handler.mjs to replace the stub logic.`,
  };
}

/** Used by the agent-mode tool to render the prompt code-agent sees.
 *  Kept here (not in server.mjs) so the contract between generator and
 *  agent stays in one file. */
export function buildAgentPrompt({ slug, toolName, voiceIntent, behaviour }) {
  return `You are filling in the handler.mjs for a Jarvis plugin.

Plugin slug: ${slug}
Tool name: ${toolName}
Voice intent: "${voiceIntent}"
Desired behaviour: ${behaviour}

The handler signature is:

    async function run(toolName, args, ctx) { ... }

ctx primitives available to the handler:
  - ctx.executeTool(name, args)  → call any registered tool by name (await the result)
  - ctx.broadcast(payload)       → push a WS event to the HUD ({ type, data })
  - ctx.memory                   → persistent KV store: put(k, v), get(k), list(prefix)
  - ctx.log(...)                 → tagged logger

Constraints:
  - No fs, child_process, http imports. Use globalThis.fetch for network.
  - Plugin file lives at bridge/plugins/${slug}/handler.mjs.
  - The handler must export the function as default.
  - Return a JSON-serialisable value. The string "summary" field, if present,
    is what gets spoken back to the operator via TTS — keep it under 200 chars.
  - On error, throw with a clear human-readable message.

Write the COMPLETE handler.mjs file (header comment + run() + export default).
Do not output any other text — just the JS source. The file at
bridge/plugins/${slug}/handler.mjs will be overwritten with whatever you return.`;
}
